import { contextBridge, ipcRenderer, webUtils } from 'electron';

contextBridge.exposeInMainWorld('flashDesktop', {
  minimize: () => ipcRenderer.send('window:minimize'),
  maximize: () => ipcRenderer.send('window:maximize'),
  close: () => ipcRenderer.send('window:close'),
  openExternal: (url: string) => ipcRenderer.invoke('open-external', url),
  searchMods: (request: unknown) => ipcRenderer.invoke('mods:search', request),
  inspectJava: (customPath: string) => ipcRenderer.invoke('system:inspect-java', customPath),
  loadProfiles: (fallback: unknown) => ipcRenderer.invoke('profiles:load', fallback),
  saveProfiles: (profiles: unknown) => ipcRenderer.invoke('profiles:save', profiles),
  deleteProfile: (id: string) => ipcRenderer.invoke('profiles:delete', id),
  duplicateProfile: (sourceId: string, profile: unknown) => ipcRenderer.invoke('profiles:duplicate', sourceId, profile),
  openProfileFolder: (id: string) => ipcRenderer.invoke('profiles:open-folder', id),
  exportProfile: (profile: unknown) => ipcRenderer.invoke('profiles:export', profile),
  importProfile: (existingIds: string[]) => ipcRenderer.invoke('profiles:import', existingIds),
  listProfileMods: (profileId: string) => ipcRenderer.invoke('content:list-mods', profileId),
  chooseModFiles: (profileId: string) => ipcRenderer.invoke('content:choose-mods', profileId),
  importModFiles: (profileId: string, paths: string[]) => ipcRenderer.invoke('content:import-mods', profileId, paths),
  setModEnabled: (profileId: string, fileName: string, enabled: boolean) => ipcRenderer.invoke('content:set-enabled', profileId, fileName, enabled),
  getPathForFile: (file: File) => webUtils.getPathForFile(file),
  listModrinthVersions: (projectId: string, gameVersion: string, loader: string) => ipcRenderer.invoke('content:modrinth-versions', projectId, gameVersion, loader),
  installModrinthVersion: (profileId: string, versionId: string, gameVersion: string, loader: string) => ipcRenderer.invoke('content:install-modrinth', profileId, versionId, gameVersion, loader),
  curseForgeKeyStatus: () => ipcRenderer.invoke('curseforge:key-status'),
  saveCurseForgeKey: (key: string) => ipcRenderer.invoke('curseforge:save-key', key),
  clearCurseForgeKey: () => ipcRenderer.invoke('curseforge:clear-key'),
  loadFavoriteServers: () => ipcRenderer.invoke('servers:load-favorites'),
  addFavoriteServer: (name: string, address: string) => ipcRenderer.invoke('servers:add-favorite', name, address),
  removeFavoriteServer: (id: string) => ipcRenderer.invoke('servers:remove-favorite', id),
  serverStatus: (id: string) => ipcRenderer.invoke('servers:status', id),
});
